	name := "历史说明插件"
	legacy := "# 历史说明插件\n\n## 说明\n\n- 包含 1 个已编译插件（.smx）\n\n---\n\n" +
		"本说明由面板根据插件目录内的实际文件与配置自动整理，未包含推测内容。\n"

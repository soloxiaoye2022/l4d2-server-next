// SourceMod 扩展（sourcemod/extensions 下的 .so/.dll）不能算成 Metamod 扩展。
// 真实目录：自选-Neko多特-NS7 带 BinHooks.ext.so + Neko_Specials_binhooks.smx
func TestGeneratePluginReadmeSeparatesSourceModExtensions(t *testing.T) {
	store := withPluginStore(t)
	name := "自选-Neko多特-NS7(himenekocn)"
	pluginDir := writePluginFixture(t, store, name, map[string]string{
		"left4dead2/addons/sourcemod/plugins/Neko_Specials_binhooks.smx": "fake",
		"left4dead2/addons/sourcemod/extensions/BinHooks.ext.so":         "elf",
		"left4dead2/addons/sourcemod/extensions/BinHooks.ext.dll":        "pe",
		"left4dead2/addons/sourcemod/extensions/BinHooks.autoload":       "BinHooks",
	})

	previous := executePluginRconCommand
	executePluginRconCommand = func(command string) (string, error) {
		return "[SM] Plugin \"Neko_Specials_binhooks.smx\" was not found.\n", nil
	}
	t.Cleanup(func() { executePluginRconCommand = previous })

	if _, err := GeneratePluginReadme(name); err != nil {
		t.Fatalf("GeneratePluginReadme() error = %v", err)
	}

	content, _ := os.ReadFile(filepath.Join(pluginDir, "README.md"))
	text := string(content)
	if strings.Contains(text, "## Metamod 扩展") {
		t.Fatalf("SourceMod 扩展不能被归到 Metamod:\n%s", text)
	}
	if !strings.Contains(text, "## SourceMod 扩展") {
		t.Fatalf("应单独列出 SourceMod 扩展:\n%s", text)
	}
	if !strings.Contains(text, "BinHooks.ext.so") {
		t.Fatalf("应列出扩展文件:\n%s", text)
	}
	if strings.Contains(text, "这是 Metamod 扩展") {
		t.Fatalf("有 smx 的插件不该被判成 Metamod:\n%s", text)
	}
}


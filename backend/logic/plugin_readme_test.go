// 从未加载插件的 .sp 源码解析命令，覆盖 RegConsoleCmd 与 RegAdminCmd 两种写法。
func TestParseSourcePluginCommands(t *testing.T) {
	source := `public void OnPluginStart()
{
	RegConsoleCmd("sm_hp", Command_Reset, "生还者过关时自动满血或复活.");
	RegConsoleCmd("sm_hud", CommandSwitchHud, "开启或关闭所有HUD.");
	RegAdminCmd("sm_limit", cmdSetLimit, ADMFLAG_RCON, "设置特感生成数量");
	RegAdminCmd("sm_type", cmdType, ADMFLAG_ROOT, "随机轮换模式");
	RegConsoleCmd("sm_noh", Command_NoHelp);
}`
	files := map[string]string{"plugin.sp": source}
	commands := parseSourcePluginCommands([]string{"plugin.sp"}, func(rel string) ([]byte, error) {
		body, ok := files[rel]
		if !ok {
			return nil, os.ErrNotExist
		}
		return []byte(body), nil
	})

	if len(commands) != 5 {
		t.Fatalf("解析到 %d 条，期望 5: %+v", len(commands), commands)
	}

	byName := map[string]PluginCommand{}
	for _, c := range commands {
		byName[c.Command] = c
	}
	if got := byName["sm_hp"]; got.Type != "console" || !strings.Contains(got.Help, "满血") {
		t.Fatalf("sm_hp 解析错误: %+v", got)
	}
	if got := byName["sm_limit"]; got.Type != "rcon" || got.Help != "设置特感生成数量" {
		t.Fatalf("sm_limit 应带 rcon 权限与说明: %+v", got)
	}
	if got := byName["sm_type"]; got.Type != "root" {
		t.Fatalf("sm_type 权限应为 root: %+v", got)
	}
	if got := byName["sm_noh"]; got.Help != "" {
		t.Fatalf("无帮助文本时不应编造: %+v", got)
	}
}

